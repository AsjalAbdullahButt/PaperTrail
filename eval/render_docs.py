"""Inject the generated result tables into the prose documents.

``run_eval.py`` and ``analysis.py`` write each table to ``results/tables/<name>.md``.
The written deliverables mark where a table belongs and this script fills it in, so
no result number is ever typed by hand and every document shows the same figures.

Markdown documents (REPORT.md, chunking_comparison.md, PRESENTATION.md)::

    <!-- BEGIN:retrieval -->
    <!-- END:retrieval -->

The plain-text report (Report.txt, for manual grading) uses::

    [[BEGIN:retrieval]]
    [[END:retrieval]]

and receives the same table re-flowed as aligned monospace columns. A table that
the last run did not produce is replaced by an explicit "not yet generated" notice
instead of stale numbers. Besides the run tables, two built-ins exist: ``manifest``
(corpus table from dataset/manifest.csv) and ``testset_stats``.

    python render_docs.py
"""
from __future__ import annotations

import csv
import json
import pathlib
import re
import textwrap
from collections import Counter

EVAL_DIR = pathlib.Path(__file__).resolve().parent
TABLES = EVAL_DIR / "results" / "tables"
MD_DOCS = ["REPORT.md", "chunking_comparison.md", "PRESENTATION.md"]
TXT_DOCS = ["Report.txt"]
_MD_BLOCK = re.compile(r"(<!-- BEGIN:(\w+) -->)\n.*?(<!-- END:\2 -->)", re.DOTALL)
_TXT_BLOCK = re.compile(r"(\[\[BEGIN:(\w+)\]\])\n.*?(\[\[END:\2\]\])", re.DOTALL)
_MISSING = ("_Not generated by the last run. Run `python run_eval.py` / `python analysis.py` (with the LLM key in "
            "`backend/.env` where needed) and then `python render_docs.py`._")


def manifest_table() -> str:
    """Corpus table built from dataset/manifest.csv (the provenance record)."""
    with (EVAL_DIR / "dataset" / "manifest.csv").open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines = ["| doc_id | Title | Authors | Year | Words | Pages | Source |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r['doc_id']}` | {r['title']} | {r['authors']} | {r['year']} | {int(r['n_words']):,} | "
                     f"{r['n_pages']} | [{r['arxiv_id_or_url'].rsplit('/', 1)[-1]}]({r['arxiv_id_or_url']}) |")
    words = [int(r["n_words"]) for r in rows]
    pages = [int(r["n_pages"]) for r in rows]
    lines += ["", f"**{len(rows)} papers, {sum(words):,} words, {sum(pages)} pages** "
              f"(per paper: {min(words):,}–{max(words):,} words, {min(pages)}–{max(pages)} pages)."]
    return "\n".join(lines)


def testset_table() -> str:
    items = json.loads((EVAL_DIR / "testset.json").read_text(encoding="utf-8"))
    c = Counter(i["type"] for i in items)
    return (f"{len(items)} questions: {c['factual']} factual, {c['multi_hop']} multi-hop (evidence in two papers), "
            f"{c['unanswerable']} unanswerable (answer deliberately absent from the corpus).")


_GENERATED = {"manifest": manifest_table, "testset_stats": testset_table}


def _body(name: str) -> str:
    if name in _GENERATED:
        return _GENERATED[name]()
    path = TABLES / f"{name}.md"
    return path.read_text(encoding="utf-8").strip() if path.exists() else _MISSING


def render(text: str) -> str:
    """Markdown flavour."""
    return _MD_BLOCK.sub(lambda m: f"{m.group(1)}\n{_body(m.group(2))}\n{m.group(3)}", text)


# ------------------------------ plain text ------------------------------- #
def _plain(cell: str) -> str:
    cell = re.sub(r"\[([^\]]+)\]\((https?://[^)]+)\)", r"\1", cell)   # [text](url) -> text
    cell = re.sub(r"^\s*_(.*)_\s*$", r"\1", cell)                      # _italic notice_ -> italic notice
    cell = re.sub(r"\*\*(.+?)\*\*", r"\1", cell)
    cell = re.sub(r"(?<![\w*])\*(\S[^*]*?\S)\*(?![\w*])", r"\1", cell)   # *emphasis* -> emphasis (a lone trailing "*" is kept)
    return cell.replace("`", "").strip()


def md_to_text(md: str, width: int = 100) -> str:
    """Re-flow markdown tables as aligned monospace columns and wrap paragraphs."""
    out: list[str] = []
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.lstrip().startswith("|"):
            block = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                block.append(lines[i])
                i += 1
            rows = [[_plain(c) for c in row.strip().strip("|").split("|")] for row in block
                    if not re.fullmatch(r"\s*\|?[\s:\-|]+\|?\s*", row)]
            if rows:
                ncol = max(len(r) for r in rows)
                rows = [r + [""] * (ncol - len(r)) for r in rows]
                widths = [max(len(r[c]) for r in rows) for c in range(ncol)]
                for n, r in enumerate(rows):
                    out.append("  " + "  ".join(r[c].ljust(widths[c]) for c in range(ncol)).rstrip())
                    if n == 0:
                        out.append("  " + "  ".join("-" * widths[c] for c in range(ncol)))
            continue
        stripped = _plain(line) if not line.startswith("###") else line.lstrip("# ").strip().upper()
        if not stripped:
            out.append("")
        elif line.startswith(("- ", "* ")):
            out.append(textwrap.fill(_plain(line[2:]), width, initial_indent="  - ", subsequent_indent="    "))
        else:
            out.append(textwrap.fill(stripped, width, initial_indent="  ", subsequent_indent="  "))
        i += 1
    return "\n".join(out).rstrip()


def render_text(text: str) -> str:
    return _TXT_BLOCK.sub(lambda m: f"{m.group(1)}\n{md_to_text(_body(m.group(2)))}\n{m.group(3)}", text)


def main() -> None:
    for names, fn in ((MD_DOCS, render), (TXT_DOCS, render_text)):
        for name in names:
            path = EVAL_DIR / name
            if not path.exists():
                continue
            old = path.read_text(encoding="utf-8")
            new = fn(old)
            path.write_text(new, encoding="utf-8")
            print(f"{name}: {'updated' if new != old else 'unchanged'}")


if __name__ == "__main__":
    main()
