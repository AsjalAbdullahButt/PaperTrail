"""Inject the generated result tables into the prose documents.

``run_eval.py`` writes each table to ``results/tables/<name>.md``. REPORT.md,
chunking_comparison.md and PRESENTATION.md mark where a table belongs with

    <!-- BEGIN:retrieval -->
    <!-- END:retrieval -->

and this script replaces everything between each pair of markers with the
current table, so no result number is ever typed by hand. A table that the last
run did not produce (e.g. ``generation`` after a ``--no-generate`` run) is
replaced by an explicit "not yet generated" notice instead of stale numbers.

    python render_docs.py
"""
from __future__ import annotations

import csv
import json
import pathlib
import re
from collections import Counter

EVAL_DIR = pathlib.Path(__file__).resolve().parent
TABLES = EVAL_DIR / "results" / "tables"
DOCS = ["REPORT.md", "chunking_comparison.md", "PRESENTATION.md"]
_BLOCK = re.compile(r"(<!-- BEGIN:(\w+) -->)\n.*?(<!-- END:\2 -->)", re.DOTALL)
_MISSING = ("_Not generated by the last run. Run `python run_eval.py` (with a valid LLM key in "
            "`backend/.env`) and then `python render_docs.py`._")


def manifest_table() -> str:
    """Corpus table built from dataset/manifest.csv (the provenance record)."""
    with (EVAL_DIR / "dataset" / "manifest.csv").open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines = ["| doc_id | Title | Authors | Year | Words | Pages | Source |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r['doc_id']}` | {r['title']} | {r['authors']} | {r['year']} | {int(r['n_words']):,} | "
                     f"{r['n_pages']} | [{r['arxiv_id_or_url'].rsplit('/', 1)[-1]}]({r['arxiv_id_or_url']}) |")
    words = [int(r["n_words"]) for r in rows]
    pages = [int(r["n_pages"]) for r in rows]
    lines += ["", f"**{len(rows)} papers, {sum(words):,} words, {sum(pages)} pages** "
              f"(per paper: {min(words):,}–{max(words):,} words, {min(pages)}–{max(pages)} pages)."]
    return "\n".join(lines)


def testset_table() -> str:
    items = json.loads((EVAL_DIR / "testset.json").read_text(encoding="utf-8"))
    c = Counter(i["type"] for i in items)
    return (f"{len(items)} questions: {c['factual']} factual, {c['multi_hop']} multi-hop (evidence in two papers), "
            f"{c['unanswerable']} unanswerable (answer deliberately absent from the corpus).")


_GENERATED = {"manifest": manifest_table, "testset_stats": testset_table}


def render(text: str) -> str:
    def sub(m: re.Match) -> str:
        name = m.group(2)
        if name in _GENERATED:
            body = _GENERATED[name]()
        else:
            path = TABLES / f"{name}.md"
            body = path.read_text(encoding="utf-8").strip() if path.exists() else _MISSING
        return f"{m.group(1)}\n{body}\n{m.group(3)}"

    return _BLOCK.sub(sub, text)


def main() -> None:
    for name in DOCS:
        path = EVAL_DIR / name
        if not path.exists():
            continue
        old = path.read_text(encoding="utf-8")
        new = render(old)
        path.write_text(new, encoding="utf-8")
        print(f"{name}: {'updated' if new != old else 'unchanged'}")


if __name__ == "__main__":
    main()
